import re
import sqlparse
from typing import Tuple

# ── DDL / DML mots-clés interdits ─────────────────────────────────────────────
FORBIDDEN_KEYWORDS = {
    "DROP", "DELETE", "UPDATE", "INSERT", "ALTER", "TRUNCATE",
    "EXEC", "EXECUTE", "CREATE", "GRANT", "REVOKE", "MERGE",
    "REINDEX", "VACUUM", "COPY", "SHUTDOWN"
}

# ── Fonctions PostgreSQL dangereuses ──────────────────────────────────────────
# Bloquent : lecture de fichiers, mise en veille de la base, config interne
FORBIDDEN_FUNCTIONS = {
    "PG_READ_FILE", "PG_SLEEP", "PG_STAT_FILE", "PG_LS_DIR",
    "PG_READ_BINARY_FILE", "CURRENT_SETTING", "SET_CONFIG",
    "PG_RELOAD_CONF", "PG_ROTATE_LOGFILE", "LO_IMPORT", "LO_EXPORT"
}

# ── Tables autorisées (liste blanche stricte) ─────────────────────────────────
ALLOWED_TABLES = {"bookings", "activities", "stays", "events"}
# Note: "admins" volontairement retiré — aucune requête IA ne doit y toucher


def validate_sql_safety(query: str) -> Tuple[bool, str]:
    """
    Validates that a SQL query generated by an LLM is safe, read-only,
    and cannot harm the database or leak sensitive data.

    Layers of protection:
      1. Rejects empty queries
      2. Rejects multi-statement injection (semicolon chaining)
      3. Allows only SELECT statements
      4. Blocks forbidden DDL/DML keywords
      5. Blocks the literal column name password_hash
      6. Blocks dangerous PostgreSQL built-in functions (file I/O, sleep, config)
      7. Blocks any access to the admins table
      8. Blocks PostgreSQL system catalog views (pg_shadow, pg_roles, ...)
      9. Enforces strict table allowlist — only business tables are permitted

    Returns:
        (is_safe: bool, reason: str)
    """
    cleaned = query.strip()
    if not cleaned:
        return False, "Query is empty"

    # 1. Parse into statements using sqlparse
    statements = sqlparse.parse(cleaned)
    if not statements:
        return False, "Unable to parse SQL"

    # 2. Reject multi-statement chaining (e.g., SELECT ...; DROP ...)
    if len(statements) > 1:
        return False, "Multiple SQL statements are not permitted (semicolon injection detected)."

    stmt = statements[0]

    # 3. Must be a SELECT statement
    stmt_type = stmt.get_type()
    if stmt_type != "SELECT":
        return False, f"Only SELECT queries are allowed. Attempted: '{stmt_type}'."

    # 4. Check all tokens for forbidden DDL / DML keywords
    tokens = [t.value.upper() for t in stmt.flatten() if not t.is_whitespace]
    for token in tokens:
        if token in FORBIDDEN_KEYWORDS:
            return False, f"Forbidden keyword detected in query: '{token}'."

    # 5. Block literal access to the password_hash column
    if re.search(r"\bpassword_hash\b", cleaned, re.IGNORECASE):
        return False, "Security violation: Access to admin password hashes is forbidden."

    # 6. Block dangerous PostgreSQL built-in functions
    for token in tokens:
        # strip parentheses so "PG_SLEEP(" matches "PG_SLEEP"
        bare = token.rstrip("(")
        if bare in FORBIDDEN_FUNCTIONS:
            return False, f"Forbidden PostgreSQL function: '{token}'. File I/O, sleep, and config functions are not allowed."

    # 7. Block any direct access to the admins table
    if re.search(r"\badmins\b", cleaned, re.IGNORECASE):
        return False, "Security violation: Direct access to the admins table is forbidden."

    # 8. Block PostgreSQL system catalog views (pg_shadow, pg_roles, pg_user, ...)
    if re.search(r"\bpg_[a-z_]+\b", cleaned, re.IGNORECASE):
        return False, "Security violation: Access to PostgreSQL system catalogs is forbidden."

    # 9. Enforce strict table allowlist — reject any table not in ALLOWED_TABLES
    # Extract identifiers that appear after FROM or JOIN keywords
    from_pattern = re.findall(
        r"\b(?:FROM|JOIN)\s+([a-z_][a-z0-9_]*)\b", cleaned, re.IGNORECASE
    )
    for table in from_pattern:
        if table.lower() not in ALLOWED_TABLES:
            return False, (
                f"Access to table '{table}' is not permitted. "
                f"Allowed tables: {', '.join(sorted(ALLOWED_TABLES))}."
            )

    return True, "Safe read-only SELECT query."


def enforce_safety_limit(query: str, default_limit: int = 100) -> str:
    """
    Appends a LIMIT clause if one is not present to prevent query DoS.
    """
    query_clean = query.strip().rstrip(";")
    if not re.search(r"\bLIMIT\s+\d+\b", query_clean, re.IGNORECASE):
        return f"{query_clean} LIMIT {default_limit};"
    return f"{query_clean};"
